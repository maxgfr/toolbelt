export const NAMED: ReadonlyMap<string, number> = (() => {
  const m = new Map<string, number>();
  LATIN1.forEach((name, i) => {
    m.set(name, 0xa0 + i);
  });
  GREEK.forEach((name, i) => {
    if (name === "-") return;
    m.set(name, 0x391 + i);
    m.set(name.toLowerCase(), 0x3b1 + i);
  });
  m.set("sigmaf", 0x3c2);
  for (const [name, cp] of OTHERS) if (!m.has(name)) m.set(name, cp);
  return m;
})();

/** Code point → preferred name (the first listed), for the code points worth naming. */
export const NAME_OF: ReadonlyMap<number, string> = (() => {
  const m = new Map<number, string>();
  for (const [name, cp] of NAMED) if (cp >= 0xa0 && !m.has(cp)) m.set(cp, name);
  for (const [name, cp] of [
    ["amp", 38],
    ["lt", 60],
    ["gt", 62],
    ["quot", 34],
  ] as const)
    m.set(cp, name);
  return m;
})();

