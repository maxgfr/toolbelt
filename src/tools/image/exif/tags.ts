/** The tag name, or "0x9c40" when unknown. */
export function tagName(ifd: IfdKind, id: number): string {
  const table = ifd === "GPS" ? GPS : ifd === "Interop" ? INTEROP : ifd === "Exif" ? EXIF : IFD0;
  return (
    table[id] ??
    (ifd === "Exif" ? IFD0[id] : ifd === "IFD0" || ifd === "IFD1" ? EXIF[id] : undefined) ??
    `0x${id.toString(16).padStart(4, "0")}`
  );
}
