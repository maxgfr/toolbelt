/**
 * The agent skill (skills/toolbelt/): bundles the CLI (cli/main.ts) into one dependency-free
 * Node script, scripts/toolbelt.mjs, and generates references/commands.md from the CLI's own
 * command registry, so the documentation never drifts from the code.
 *
 *   1. cli/gen/state-keys.ts: every tool's share-link keys, read from the views (state-keys.ts).
 *   2. skills/toolbelt/scripts/toolbelt.mjs: Bun.build, target node, ESM, minified, every
 *      dependency inlined; the views are replaced by an empty module (the CLI never renders).
 *   3. skills/toolbelt/references/commands.md, and the version in SKILL.md.
 *
 * Deterministic: running it twice leaves skills/ and cli/gen/ unchanged.
 */
import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import type { BunPlugin } from "bun";
import { stateKeyMap } from "./state-keys";

const ROOT = resolve(import.meta.dir, "..");
const SKILL = join(ROOT, "skills/toolbelt");
export const BUNDLE = join(SKILL, "scripts/toolbelt.mjs");
const COMMANDS_MD = join(SKILL, "references/commands.md");
const STATE_FILE = join(ROOT, "cli/gen/state-keys.ts");

/** The tool registry lazy-loads each View; the CLI only needs the metadata, so views become stubs. */
const stubViews: BunPlugin = {
  name: "stub-views",
  setup(build) {
    build.onResolve({ filter: /\/View(\.tsx)?$/ }, (args) => ({
      path: args.path,
      namespace: "view-stub",
    }));
    build.onLoad({ filter: /.*/, namespace: "view-stub" }, () => ({
      contents: "export default function View() { return null; }",
      loader: "js",
    }));
  },
};

async function writeIfChanged(path: string, content: string | Uint8Array): Promise<boolean> {
  const next = typeof content === "string" ? new TextEncoder().encode(content) : content;
  try {
    const prev = new Uint8Array(await readFile(path));
    if (Buffer.compare(prev, next) === 0) return false;
  } catch {}
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, next);
  return true;
}

async function generateStateKeys(): Promise<void> {
  const map = await stateKeyMap(ROOT);
  const src = [
    "// biome-ignore-all lint/suspicious/noTemplateCurlyInString: `expr` holds source excerpts.",
    "// Generated by scripts/build-skill.ts from each tool's View (its useToolState calls). Do not edit.",
    'import type { StateKey } from "../../scripts/state-keys";',
    "",
    `export const STATE_KEYS: Record<string, StateKey[]> = ${JSON.stringify(map, null, 2)};`,
    "",
  ].join("\n");
  await writeIfChanged(STATE_FILE, src);
  // Biome's formatting, so `biome check` stays clean and the file is stable across runs.
  const fmt = Bun.spawnSync(
    [join(ROOT, "node_modules/.bin/biome"), "format", "--write", STATE_FILE],
    {
      cwd: ROOT,
      stdout: "pipe",
      stderr: "pipe",
    },
  );
  if (fmt.exitCode !== 0) throw new Error(`biome format failed: ${fmt.stderr.toString()}`);
}

export async function bundle(): Promise<Uint8Array> {
  const res = await Bun.build({
    entrypoints: [join(ROOT, "cli/main.ts")],
    target: "node",
    format: "esm",
    minify: true,
    splitting: false,
    sourcemap: "none",
    banner: "#!/usr/bin/env node",
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    plugins: [stubViews],
  });
  if (!res.success) {
    for (const log of res.logs) console.error(log);
    throw new Error("build-skill: bundle failed");
  }
  const [out, ...rest] = res.outputs;
  if (!out || rest.some((o) => o.kind === "chunk" || o.kind === "entry-point"))
    throw new Error("build-skill: expected a single bundle");
  return new Uint8Array(await out.arrayBuffer());
}

/** references/commands.md, from the registry. */
export async function commandsMarkdown(): Promise<string> {
  const { GROUPS, categoryTitle } = await import("../cli/registry");
  const { stateKeysMarkdown } = await import("../cli/commands/meta");
  const { VERSION } = await import("../cli/version");
  const lines: string[] = [
    "# toolbelt commands",
    "",
    `<!-- Generated by scripts/build-skill.ts from the CLI's registry (toolbelt ${VERSION}). Do not edit. -->`,
    "",
    "Run every command as `node <skill-dir>/scripts/toolbelt.mjs <command> ...`. Input: an argument,",
    "`--file <path>`, or stdin. Every command also takes `--json` (structured output), `--file`/`-f`,",
    "`--out`/`-o <path>` (write the output to a file), `--lang en|fr|de` and `--help`.",
    "Exit codes: 0 ok, 1 invalid input (message on stderr), 2 wrong usage (unknown option, missing input).",
    "",
  ];
  const all = GROUPS.flatMap((g) => g.commands);
  const browser = all.filter((c) => c.browserOnly);
  const tools = all.filter((c) => c.tool);
  lines.push(
    `${tools.length - browser.length} tools run offline in the CLI; ${browser.length} are browser-only (their command prints the link).`,
    "",
    ...GROUPS.map(
      (g) =>
        `- **${categoryTitle(g.category)}**: ${g.commands.map((c) => `\`${c.name}\`${c.browserOnly ? " (browser)" : ""}`).join(", ")}`,
    ),
    "",
  );
  for (const g of GROUPS) {
    lines.push(`## ${categoryTitle(g.category)}`, "");
    for (const c of g.commands) {
      lines.push(`### ${c.name}${c.browserOnly ? " (browser only)" : ""}`, "");
      lines.push(
        c.summary + (c.browserOnly && c.browserReason ? ` Needs ${c.browserReason}.` : ""),
        "",
      );
      if (c.aliases?.length)
        lines.push(`Aliases: ${c.aliases.map((a) => `\`${a}\``).join(", ")}.`, "");
      lines.push("```", c.usage, "```", "");
      for (const o of c.options ?? []) {
        const flag = `${o.alias ? `-${o.alias}, ` : ""}--${o.name}${o.type === "boolean" ? "" : ` ${o.arg ?? (o.values ? `<${o.values.join("|")}>` : o.type === "number" ? "<n>" : "<value>")}`}`;
        const def = o.default !== undefined ? ` Default: ${o.default}.` : "";
        lines.push(`- \`${flag}\`: ${o.desc}${def}`);
      }
      if (c.options?.length) lines.push("");
      if (c.notes) lines.push(c.notes, "");
      lines.push("Examples:", "", "```sh");
      for (const e of c.examples) lines.push(e.desc ? `${e.cmd}   # ${e.desc}` : e.cmd);
      lines.push("```", "");
      if (c.tool) lines.push(`Site: https://maxgfr.github.io/toolbelt/#/${c.tool}`, "");
    }
  }
  lines.push(
    "## Share-link state keys",
    "",
    "`toolbelt link <tool> --set key=value` accepts these keys (read from each tool's view).",
    "Computed defaults depend on the moment or the language.",
    "",
    stateKeysMarkdown(),
    "",
  );
  return lines.join("\n");
}

async function syncSkillVersion(): Promise<void> {
  const path = join(SKILL, "SKILL.md");
  const pkg = JSON.parse(await readFile(join(ROOT, "package.json"), "utf8")) as { version: string };
  let md: string;
  try {
    md = await readFile(path, "utf8");
  } catch {
    return;
  }
  await writeIfChanged(path, md.replace(/^(\s+version:\s*).*$/m, `$1${pkg.version}`));
}

if (import.meta.main) {
  const started = performance.now();
  await generateStateKeys();
  const js = await bundle();
  await writeIfChanged(BUNDLE, js);
  await chmod(BUNDLE, 0o755);
  await writeIfChanged(COMMANDS_MD, await commandsMarkdown());
  await syncSkillVersion();
  console.log(
    `skill: ${BUNDLE.slice(ROOT.length + 1)} (${(js.length / 1024).toFixed(1)} KiB), references/commands.md, in ${Math.round(performance.now() - started)} ms`,
  );
}
