/**
 * Production build: Bun.build on index.html with hashed chunks (one per tool,
 * loaded when it is opened) and relative paths (the site lives under
 * /toolbelt/), a CSP injected into the page, and a service worker that
 * precaches every file so the whole toolbox works offline.
 *
 * The CSP allows no network access at all beyond the site itself: no inline
 * script, no eval (WebAssembly compilation only, for the hash functions), no
 * third-party anything. The build fails if index.html has an inline script or
 * a reference to another origin.
 */
import { createHash } from "node:crypto";
import { cp, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");

export const CSP = [
  "default-src 'none'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "style-src 'self'",
  "connect-src 'self'",
  "img-src 'self' blob: data:",
  "media-src 'self' blob:",
  "worker-src 'self'",
  "manifest-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
].join("; ");

const DESCRIPTION =
  "Everyday utilities in your browser: character counter, text and file diff, JSON, YAML, CSV, Base64, hashes, UUIDs, regex, timestamps, cron, colors and more. Offline, nothing leaves your device.";

function headInject(): string {
  return [
    `<meta http-equiv="Content-Security-Policy" content="${CSP}" />`,
    `<meta name="referrer" content="no-referrer" />`,
    `<meta name="color-scheme" content="light dark" />`,
    `<meta name="theme-color" content="#0f766e" />`,
    `<meta name="description" content="${DESCRIPTION}" />`,
    `<meta property="og:title" content="toolbelt" />`,
    `<meta property="og:description" content="${DESCRIPTION}" />`,
    `<link rel="icon" href="./icon.svg" type="image/svg+xml" />`,
    `<link rel="manifest" href="./manifest.webmanifest" />`,
  ].join("\n    ");
}

export interface BuildOptions {
  outdir?: string;
  minify?: boolean;
}

function fail(msg: string): never {
  throw new Error(`build: ${msg}`);
}

async function listFiles(dir: string, base = dir): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listFiles(p, base)));
    else out.push(relative(base, p).split("\\").join("/"));
  }
  return out.sort();
}

/** Throws if the HTML has an inline script, inline handler, inline style or external URL. */
export function auditHtml(html: string, page = "index.html"): void {
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1] ?? "";
    const body = (m[2] ?? "").trim();
    if (!/\bsrc\s*=/.test(attrs) || body.length > 0) fail(`inline <script> found in ${page}`);
  }
  if (/\son[a-z]+\s*=/i.test(html)) fail(`inline event handler found in ${page}`);
  if (/<style\b/i.test(html)) fail(`inline <style> found in ${page}`);
  for (const m of html.matchAll(/\b(?:src|href)\s*=\s*"([^"]*)"/gi)) {
    const url = m[1] ?? "";
    if (/^(?:[a-z]+:)?\/\//i.test(url)) fail(`external URL in ${page}: ${url}`);
    if (url.startsWith("/")) fail(`absolute path in ${page} (breaks the /toolbelt/ base): ${url}`);
  }
}

/** A cache-first service worker that precaches the given files, versioned by their content. */
export function serviceWorker(files: string[], version: string): string {
  return `// Generated by scripts/build.ts: precaches every file so toolbelt works offline.
const CACHE = "toolbelt-${version}";
const FILES = ${JSON.stringify(["./", ...files.map((f) => `./${f}`)])};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)),
  );
});
`;
}

export async function build(opts: BuildOptions = {}): Promise<{ outdir: string; files: string[] }> {
  const outdir = resolve(ROOT, opts.outdir ?? "dist");
  const minify = opts.minify ?? true;
  await rm(outdir, { recursive: true, force: true });
  await mkdir(outdir, { recursive: true });

  // 1. The app, one chunk per tool.
  const app = await Bun.build({
    entrypoints: [join(ROOT, "index.html")],
    outdir,
    minify,
    splitting: true,
    target: "browser",
    format: "esm",
    naming: {
      entry: "[name].[ext]",
      chunk: "assets/[name]-[hash].[ext]",
      asset: "assets/[name]-[hash].[ext]",
    },
    define: { "process.env.NODE_ENV": JSON.stringify(minify ? "production" : "development") },
  });
  if (!app.success) {
    for (const log of app.logs) console.error(log);
    fail("app build failed");
  }

  // 2. Static files.
  await cp(join(ROOT, "public"), outdir, { recursive: true });

  // 3. Harden the page.
  const path = join(outdir, "index.html");
  let html = await readFile(path, "utf8");
  if (!/<meta charset="utf-8"\s*\/?>/i.test(html))
    fail("index.html must start with <meta charset>");
  html = html.replace(/(<meta charset="utf-8"\s*\/?>)/i, `$1\n    ${headInject()}`);
  auditHtml(html);
  await writeFile(path, html);

  // 4. The service worker, over everything else.
  const files = (await listFiles(outdir)).filter((f) => f !== "index.html");
  const hash = createHash("sha256");
  for (const f of [...files, "index.html"]) hash.update(f).update(await readFile(join(outdir, f)));
  await writeFile(join(outdir, "sw.js"), serviceWorker(files, hash.digest("hex").slice(0, 12)));

  return { outdir, files: await listFiles(outdir) };
}

if (import.meta.main) {
  const started = performance.now();
  const res = await build({ minify: !process.argv.includes("--dev") });
  let bytes = 0;
  for (const f of res.files) bytes += (await stat(join(res.outdir, f))).size;
  console.log(
    `built ${res.files.length} files (${(bytes / 1024).toFixed(1)} KiB) in ${Math.round(performance.now() - started)} ms`,
  );
}
